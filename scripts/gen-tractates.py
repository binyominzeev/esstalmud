"""Regenerates lib/tractates.ts (Bavli tractates grouped by seder, with page counts) from the Sefaria API."""
import json
import urllib.request

HU = {"Seder Zeraim": "Zeraim", "Seder Moed": "Moéd", "Seder Nashim": "Násim",
      "Seder Nezikin": "Nezikin", "Seder Kodashim": "Kodásim", "Seder Tahorot": "Toharot"}


def get(path):
    return json.load(urllib.request.urlopen("https://www.sefaria.org/api/" + path))


def find(nodes, category):
    for n in nodes:
        if n.get("category") == category and "contents" in n:
            return n
        if "contents" in n:
            r = find(n["contents"], category)
            if r:
                return r


bavli = find(get("index"), "Bavli")
lines = [
    "// Generated by scripts/gen-tractates.py from the Sefaria index API. `amudim` is the Sefaria section count (index 1 = 1a, 3 = 2a, ...).",
    "export interface Tractate { seder: string; title: string; heTitle: string; slug: string; amudim: number; }",
    "",
    "export const TRACTATES: Tractate[] = [",
]
for seder in bavli["contents"]:
    if seder["category"] not in HU:
        continue
    for c in seder["contents"]:
        n = get("index/" + c["title"].replace(" ", "_"))["schema"]["lengths"][0]
        slug = c["title"].lower().replace(" ", "-")
        lines.append(f'  {{ seder: "{HU[seder["category"]]}", title: "{c["title"]}", heTitle: "{c["heTitle"]}", slug: "{slug}", amudim: {n} }},')
lines.append("];")
open("lib/tractates.ts", "w").write("\n".join(lines) + "\n")
